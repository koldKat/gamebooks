export function combatColumn(ratio) {
  if (!Number.isSafeInteger(ratio)) throw new RangeError('Invalid combat ratio');
  if (ratio <= -11) return 0;
  if (ratio < 0) return Math.floor((ratio + 12) / 2);
  if (ratio === 0) return 6;
  return Math.min(12, 6 + Math.ceil(ratio / 2));
}

export function combatLosses(ratio, pick) {
  if (!Number.isInteger(pick) || pick < 0 || pick > 9) throw new RangeError('Invalid random number');
  return [...COMBAT_TABLE[pick === 0 ? 9 : pick - 1][combatColumn(ratio)]];
}
